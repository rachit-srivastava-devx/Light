#[test]
fn f09_t12_census_ratchet_on_the_forgery_literal() {
    const LITERAL: &str = "keel:lld-ready";
    let repo_root = PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../../.."));
    let rust_src = repo_root.join("fleet/keel/fleet/src");
    let python_src = repo_root.join("orb/backend/relay-py/src");

    let mut files_scanned = 0usize;
    let mut files_with_literal: Vec<String> = Vec::new();

    for (root, ext) in [(&rust_src, "rs"), (&python_src, "py")] {
        for entry in walk_files(root) {
            if entry.extension().and_then(|e| e.to_str()) != Some(ext) {
                continue;
            }
            files_scanned += 1;
            let text = fs::read_to_string(&entry).unwrap_or_default();
            if text.contains(LITERAL) {
                let relative = entry
                    .strip_prefix(&repo_root)
                    .unwrap_or(&entry)
                    .to_string_lossy()
                    .replace('\\', "/");
                files_with_literal.push(relative);
            }
        }
    }

    assert!(
        files_scanned > 0,
        "measuring nothing is a failure -- the walk found no source files"
    );

    files_with_literal.sort();
    files_with_literal.dedup();
    let mut allowed = vec![
        "fleet/keel/fleet/src/lld.rs".to_string(),
        "fleet/keel/fleet/src/lld_ready.rs".to_string(),
        "orb/backend/relay-py/src/orb_relay/proxy/lld_schemas.py".to_string(),
    ];
    allowed.sort();

    assert_eq!(
        files_with_literal, allowed,
        "the forgery literal must appear in EXACTLY the allowed validator-constant sites -- \
         equality, not `contains`. If this now includes handoff.py/app.py/freeze.rs, the orb or \
         the new keel command started constructing the string itself rather than referencing the \
         gate's own const."
    );
}

fn walk_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else {
        return out;
    };
    for entry in entries.filter_map(|e| e.ok()) {
        let path = entry.path();
        if path.is_dir() {
            out.extend(walk_files(&path));
        } else {
            out.push(path);
        }
    }
    out
}

