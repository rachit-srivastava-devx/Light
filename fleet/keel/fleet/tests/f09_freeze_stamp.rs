//! F09: the contract suite for `fleet freeze stamp <brief.json> --out <lld.json>` (lane contract
//! `docs/lane-contracts/F09-orb-fleet-handoff.md` §7.1). Cargo INTEGRATION test -- drives the real
//! compiled `fleet` binary via subprocess for every CLI-observable property (exit codes, stdout/
//! stderr framing, on-disk ledger/`--out` side effects), and calls directly into `fleet::freeze` /
//! `fleet::lld_ready` for the two properties the CLI cannot reach (F09-T5's `MeasuredNothing`
//! branch) or that are cleaner to pin as a pure projection (F09-T10's exact literals).
//!
//! Per the lane contract's own instruction to this suite's builder: do not edit this file beyond
//! *adding* cases. Any diff that changes or removes an assertion below is a contract breach.
//! Fixtures needed beyond the read-only corpus (`fleet/contracts/fixtures/lld/**`, never edited)
//! are built in a tempdir at test runtime, matching `tests/f07_sow_intake.rs`'s own convention.

use fleet::freeze;
use fleet::lld;
use fleet::lld_ready::{self, GateRefs, Outcome};
use serde_json::{json, Value};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn fleet_bin() -> &'static str {
    env!("CARGO_BIN_EXE_fleet")
}

fn fixtures_dir() -> PathBuf {
    PathBuf::from(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../contracts/fixtures/lld"
    ))
}

fn load_fixture(name: &str) -> Value {
    let text = fs::read_to_string(fixtures_dir().join(format!("{name}.json")))
        .unwrap_or_else(|error| panic!("read fixture {name}: {error}"));
    serde_json::from_str(&text).unwrap_or_else(|error| panic!("parse fixture {name}: {error}"))
}

fn unique_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "fleet-f09-{tag}-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos()
    ));
    fs::create_dir_all(&dir).expect("create fixture dir");
    dir
}

fn write_temp_json(dir_tag: &str, file_name: &str, value: &Value) -> PathBuf {
    let dir = unique_dir(dir_tag);
    let path = dir.join(file_name);
    fs::write(
        &path,
        serde_json::to_vec_pretty(value).expect("serialize temp fixture"),
    )
    .expect("write temp fixture");
    path
}

fn refs() -> GateRefs {
    let owners_text = fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../contracts/owners.v1.json"
    ))
    .expect("read owners.v1.json");
    let owners_json: Value = serde_json::from_str(&owners_text).expect("parse owners.v1.json");
    let owners: Vec<String> = owners_json["owners"]
        .as_array()
        .expect("owners array")
        .iter()
        .map(|v| v.as_str().expect("owner is a string").to_string())
        .collect();

    let refs_text = fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../contracts/gate-refs.v1.json"
    ))
    .expect("read gate-refs.v1.json");
    let refs_json: Value = serde_json::from_str(&refs_text).expect("parse gate-refs.v1.json");
    let registry_paths: Vec<String> = refs_json["registry_paths"]
        .as_array()
        .expect("registry_paths array")
        .iter()
        .map(|v| v.as_str().expect("registry path is a string").to_string())
        .collect();
    let known_node_ids: Vec<String> = refs_json["known_node_ids"]
        .as_array()
        .expect("known_node_ids array")
        .iter()
        .map(|v| v.as_str().expect("known node id is a string").to_string())
        .collect();

    GateRefs {
        owners,
        registry_paths,
        known_node_ids,
    }
}

fn run_freeze_stamp(state: &Path, brief_path: &Path, out_path: &Path) -> Output {
    Command::new(fleet_bin())
        .arg("freeze")
        .arg("stamp")
        .arg(brief_path)
        .arg("--out")
        .arg(out_path)
        .env("FLEET_STATE", state)
        .output()
        .expect("run fleet freeze stamp")
}

fn run_gate_lld_ready(path: &Path) -> Output {
    Command::new(fleet_bin())
        .args(["gate", "lld-ready"])
        .arg(path)
        .output()
        .expect("run fleet gate lld-ready")
}

fn run_sow_lld(state: &Path, lld_path: &Path) -> Output {
    Command::new(fleet_bin())
        .arg("sow")
        .arg("--lld")
        .arg(lld_path)
        .env("FLEET_STATE", state)
        .output()
        .expect("run fleet sow --lld")
}

fn stdout_of(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}
fn stderr_of(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

fn field(text: &str, prefix: &str, key: &str) -> Option<String> {
    text.lines()
        .find_map(|line| line.strip_prefix(prefix))?
        .split_whitespace()
        .find_map(|token| token.split_once('=').filter(|(k, _)| *k == key))
        .map(|(_, v)| v.to_string())
}

fn sows_in(state: &Path) -> Vec<PathBuf> {
    fs::read_dir(state.join("sows"))
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .map(|entry| entry.path())
                .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
                .collect()
        })
        .unwrap_or_default()
}

fn freezes_for(state: &Path, node_id: &str) -> Vec<PathBuf> {
    fs::read_dir(state.join("freezes").join(node_id))
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .map(|entry| entry.path())
                .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
                .collect()
        })
        .unwrap_or_default()
}

/// Any `.<name>.tmp-<pid>`-shaped residue anywhere directly under `dir` -- the atomic temp+rename
/// convention every on-disk write in this crate uses (`write_json_atomic`, `sow::write_atomic`).
fn tmp_residue_in(dir: &Path) -> Vec<PathBuf> {
    fs::read_dir(dir)
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .map(|entry| entry.path())
                .filter(|path| {
                    path.file_name()
                        .and_then(|name| name.to_str())
                        .is_some_and(|name| name.contains(".tmp-"))
                })
                .collect()
        })
        .unwrap_or_default()
}

fn cleanup(dirs: &[&Path]) {
    for dir in dirs {
        fs::remove_dir_all(dir).ok();
    }
}

