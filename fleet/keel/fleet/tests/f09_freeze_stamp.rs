#[test]
fn f09_t7_idempotency() {
    let state = unique_dir("t7-state");
    let out_dir = unique_dir("t7-out");
    let brief_path = fixtures_dir().join("complete_module.json");

    let out1 = out_dir.join("lld-1.json");
    let stamp1 = run_freeze_stamp(&state, &brief_path, &out1);
    assert_eq!(
        stamp1.status.code(),
        Some(0),
        "stderr:\n{}",
        stderr_of(&stamp1)
    );
    let stdout1 = stdout_of(&stamp1);
    let freeze_id_1 = field(&stdout1, "FREEZE_STAMPED ", "freeze_id").unwrap();
    let version_1 = field(&stdout1, "FREEZE_STAMPED ", "version").unwrap();

    let out2 = out_dir.join("lld-2.json");
    let stamp2 = run_freeze_stamp(&state, &brief_path, &out2);
    assert_eq!(
        stamp2.status.code(),
        Some(0),
        "stderr:\n{}",
        stderr_of(&stamp2)
    );
    let stdout2 = stdout_of(&stamp2);
    let freeze_id_2 = field(&stdout2, "FREEZE_STAMPED ", "freeze_id").unwrap();
    let version_2 = field(&stdout2, "FREEZE_STAMPED ", "version").unwrap();

    assert_eq!(
        freeze_id_1, freeze_id_2,
        "re-stamping an identical brief must yield the same freeze_id"
    );
    assert_eq!(
        version_1, version_2,
        "re-stamping an identical brief must yield the same version"
    );
    assert_eq!(version_1, "1");

    let ledger_files = freezes_for(&state, "lld-v1-schema");
    assert_eq!(
        ledger_files.len(),
        1,
        "an idempotent re-stamp must not append a second ledger entry"
    );

    cleanup(&[&state, &out_dir]);
}

