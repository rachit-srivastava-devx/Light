    assert_eq!(
        field(&stdout, "FREEZE_STAMPED ", "node_id").as_deref(),
        Some("lld-v1-schema")
    );
    assert_eq!(
        field(&stdout, "FREEZE_STAMPED ", "version").as_deref(),
        Some("1")
    );
    let content_hash =
        field(&stdout, "FREEZE_STAMPED ", "content_hash").expect("content_hash field");
