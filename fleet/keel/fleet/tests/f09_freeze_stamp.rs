#[test]
fn f09_t4_exit_code_parity_with_gate_lld_ready_a_census_of_four_conditions() {
    let mut not_ready = load_fixture("complete_module");
    not_ready["open_questions"] = json!(["what store?"]);
    let not_ready_path = write_temp_json("t4-not-ready", "brief.json", &not_ready);

    let shape_invalid_path = fixtures_dir().join("one_line_freeze.json");

    let nonexistent_dir = unique_dir("t4-nonexistent");
    let nonexistent_path = nonexistent_dir.join("does-not-exist.json");

    let malformed_dir = unique_dir("t4-malformed");
    let malformed_path = malformed_dir.join("malformed.json");
    fs::write(&malformed_path, b"{not valid json").expect("write malformed fixture");

    let cases: [(&str, &Path); 4] = [
        ("NotReady", &not_ready_path),
        ("ShapeInvalid", &shape_invalid_path),
        ("NonexistentPath", &nonexistent_path),
        ("MalformedJson", &malformed_path),
    ];
    assert_eq!(
        cases.len(),
        4,
        "this is a census over exactly 4 shared conditions, not a sample"
    );

    for (label, path) in cases {
        let state = unique_dir(&format!("t4-state-{label}"));
        let out_dir = unique_dir(&format!("t4-out-{label}"));
        let out_path = out_dir.join("lld.json");

        let stamp_out = run_freeze_stamp(&state, path, &out_path);
        let gate_out = run_gate_lld_ready(path);
        assert_eq!(
            stamp_out.status.code(),
            gate_out.status.code(),
            "case {label}: freeze stamp exit {:?} must equal gate lld-ready exit {:?}",
            stamp_out.status.code(),
            gate_out.status.code()
        );
        assert!(
            !out_path.exists(),
            "case {label}: a refusal must never create the --out file"
        );
        cleanup(&[&state, &out_dir]);
    }
    cleanup(&[&nonexistent_dir, &malformed_dir]);
}

