#[test]
fn f09_t5_measured_nothing_never_stamps() {
    let brief = load_fixture("complete_module");
    let r = refs();

    // Not reachable through the CLI (which always calls `check_and_evaluate`, over the real
    // 14-check vocabulary) -- F06's own pub seam, used directly, exactly as the lane contract
    // names it.
    let verdict = lld_ready::evaluate_with(&brief, &r, &[]);
    assert_eq!(verdict.outcome, Outcome::MeasuredNothing);

    let projected = freeze::project_freeze(
        &brief,
        &verdict,
        "sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        "fz-0000000000000000",
        1,
        None,
    );
    assert!(
        projected.is_none(),
        "a MeasuredNothing verdict must never produce a freeze"
    );

    // Control: the SAME brief IS Ready under the real evaluator, and DOES project -- this is not
    // a bad fixture wearing a MeasuredNothing costume.
    let real_verdict = lld_ready::evaluate(&brief, &r);
    assert_eq!(real_verdict.outcome, Outcome::Ready);
    let projected_real = freeze::project_freeze(
        &brief,
        &real_verdict,
        "sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        "fz-0000000000000000",
        1,
        None,
    );
    assert!(projected_real.is_some());
}

